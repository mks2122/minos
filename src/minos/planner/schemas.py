"""Tool schemas for the model-backed planner.

Explicit, not generated by reflection. This is the boundary where an untrusted
model's output becomes a structured request, so being able to read the exact
shape of every accepted input in one file is worth more than the convenience of
deriving it.

Every schema sets ``additionalProperties: false`` and lists ``required``, which
is what ``strict: true`` needs in order to guarantee the arguments validate.
"""

from __future__ import annotations

from typing import Any

__all__ = ["FINISH_TOOL", "operation_for_tool", "tool_definitions"]


def _tool(
    name: str, description: str, properties: dict[str, Any], required: list[str]
) -> dict[str, Any]:
    return {
        "name": name,
        "description": description,
        "input_schema": {
            "type": "object",
            "properties": properties,
            "required": required,
            "additionalProperties": False,
        },
        "strict": True,
    }


